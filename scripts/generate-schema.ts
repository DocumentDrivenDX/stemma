// Reads the UMF record schema (CONTRACT-001 A) and writes the compact table the
// validator uses. Run: ./.tools/bun scripts/generate-schema.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
export const SCHEMA_PATH = join(root, "docs/stemma/02-design/contracts/schemas/stemma-record.umf.json");
export const OUTPUT_PATH = join(root, "packages/records/src/schema.generated.ts");

interface UmfField { type: { kind: string; name?: string; target?: { element: string } }; cardinality: string }
interface UmfElement {
  id: string; kind: string; name: string; nullability?: string;
  allowedValues?: { string?: string }[];
  members?: { element: string }[];
  extensions?: { "umf.ddd"?: { kind?: string; fields?: Record<string, UmfField> } };
}

export function generate(): string {
  const module = JSON.parse(readFileSync(SCHEMA_PATH, "utf8")).modules[0];
  const elements = new Map<string, UmfElement>((module.elements as UmfElement[]).map((e) => [e.id, e]));
  const types: Record<string, Record<string, object>> = {};
  const kinds: Record<string, string> = {};
  for (const element of elements.values()) {
    const ddd = element.extensions?.["umf.ddd"];
    if (element.kind !== "record" || !ddd) continue;
    const fields: Record<string, object> = {};
    for (const member of element.members ?? []) {
      const field = elements.get(member.element)!;
      const typed = ddd.fields![field.name]!;
      const values = field.allowedValues?.map((v) => v.string);
      fields[field.name] = {
        type: typed.type.kind === "scalar" ? typed.type.name : { value: typed.type.target!.element },
        ...(field.nullability === "required" ? { required: true } : {}),
        ...(typed.cardinality === "many" ? { many: true } : {}),
        ...(values ? { values } : {}),
      };
      if (ddd.kind === "entity" && field.name === "kind") kinds[values![0]!] = element.id;
    }
    types[element.id] = fields;
  }
  const references: Record<string, string[]> = {};
  for (const relation of module.relationships as { name: string; target: { element: string }[] }[]) {
    const targets = relation.target.map((t) => Object.keys(kinds).find((k) => kinds[k] === t.element) ?? "project");
    references[relation.name] = targets;
  }
  const literal = (value: object) => JSON.stringify(value, null, 1);
  return [
    "// Generated by scripts/generate-schema.ts from stemma-record.umf.json. Do not edit.",
    "export interface FieldSpec { type: string | { value: string }; required?: boolean; many?: boolean; values?: string[] }",
    `export const TYPES: Record<string, Record<string, FieldSpec>> = ${literal(types)};`,
    `export const KIND_TYPES: Record<string, string> = ${literal(kinds)};`,
    `export const REFERENCES: Record<string, string[]> = ${literal(references)};`,
    "",
  ].join("\n");
}

if (import.meta.main) writeFileSync(OUTPUT_PATH, generate());
