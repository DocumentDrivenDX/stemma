// The committed website content must match what the current code prints, and no
// tracked website file may hold a path from the machine that made it.
import { describe, expect, test } from "bun:test";
import { appendFileSync, cpSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { GENERATED, LOCAL_PATH, normalise, staleness } from "../website/generate.ts";
import { colorTokens, contrast, measured, PAIRS } from "../website/lib/contrast.ts";
import { RECORDED, recordExample } from "../website/record-example.ts";
import { ROOT, temporary } from "./helpers.ts";

/** Website files git tracks or would add. */
const websiteFiles = (): string[] => {
  const git = Bun.spawnSync(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard", "website"], { cwd: ROOT });
  if (git.exitCode !== 0) throw new Error(git.stderr.toString());
  return git.stdout.toString().split("\0").filter(Boolean);
};

describe("generated website content", () => {
  test("is current", async () => {
    expect(await staleness()).toEqual([]);
  }, 60_000);

  test("an edit, an extra file or a changed screenshot is reported", async () => {
    const copy = join(temporary(), "generated");
    cpSync(GENERATED, copy, { recursive: true });
    appendFileSync(join(copy, "transcripts/check-clean.txt"), "edited\n");
    appendFileSync(join(copy, "screenshots/check-clean.png"), "x");
    appendFileSync(join(copy, "left-over.txt"), "x");
    expect((await staleness(copy)).sort()).toEqual([
      "changed by hand: screenshots/check-clean.png",
      "not generated by the current code: left-over.txt",
      "stale: transcripts/check-clean.txt",
    ]);
  }, 60_000);

  test("holds no local path", () => {
    const files = websiteFiles();
    expect(files).toContain("website/generated/transcripts/demo.txt");
    const bad = files.filter((file) => {
      if (file.endsWith(".png")) return false;
      const text = readFileSync(join(ROOT, file), "utf8");
      // generate.ts spells out the patterns it rejects.
      if (file === "website/generate.ts") return text.includes(homedir());
      return LOCAL_PATH.test(text) || text.includes(homedir());
    });
    expect(bad).toEqual([]);
  });

  test("the generator refuses to leave a local path", () => {
    const sample = ["", "Users", "someone", "book"].join("/");
    expect(() => normalise(`saved to ${sample}`, [])).toThrow("local path");
    expect(normalise(`saved to ${sample}`, [[sample, "$DEMO"]])).toBe("saved to $DEMO");
  });
});

describe("recorded runs of the worked example", () => {
  test("match a fresh run", async () => {
    for (const [path, text] of await recordExample()) expect(readFileSync(join(RECORDED, path), "utf8")).toBe(text);
  }, 60_000);

  test("show what the site says they show", () => {
    const checked = readFileSync(join(RECORDED, "example-check.txt"), "utf8");
    expect(checked).toContain("OPEN FINDINGS: 8 problem(s), 2 could not be checked, 0 kind(s)");
    // Nothing is open about the citations: what is open concerns source details and one page label.
    expect(checked).not.toMatch(/\[(quote\.present|quote\.page|locator\.extent|cite\.key|source\.held)[\],]/);
    expect(checked).not.toContain("cit-darwinreefs0001\n       citation file");
    expect(checked).toContain("deny-|ing");
    const trial = readFileSync(join(RECORDED, "example-trial.txt"), "utf8");
    // The two planted mistakes add exactly three findings: the impossible page is reported twice.
    expect(trial).toContain("OPEN FINDINGS: 11 problem(s), 2 could not be checked");
    for (const planted of ["[locator.extent]", "[quote.page]", "[quote.present]"]) expect(trial).toContain(planted);
    expect(trial).toContain("locator: page 412");
    expect(trial).toContain("found on: printed page 88");
    expect(trial).toContain("this view inapplicable to the smaller number of atolls");
    expect(trial).toContain("greater number of atolls");
  });
});

describe("design tokens", () => {
  test("every pairing that may carry meaning meets its contrast floor, light and dark", () => {
    expect(colorTokens()).toHaveLength(12);
    expect(contrast("#000000", "#ffffff")).toBeCloseTo(21, 5);
    for (const mode of ["light", "dark"] as const) {
      expect(measured(mode).filter((p) => p.ratio < p.floor)).toEqual([]);
    }
    expect(PAIRS).toHaveLength(22);
  });

  test("DESIGN.md lists the same color values as the stylesheet", () => {
    const design = readFileSync(join(ROOT, "docs/stemma/02-design/DESIGN.md"), "utf8");
    for (const t of colorTokens()) {
      expect(design).toContain(`\`${t.name}\``);
      expect(design).toContain(`\`${t.light}\``);
      expect(design).toContain(`\`${t.dark}\``);
    }
  });
});
